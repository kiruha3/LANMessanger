def _bb_license():
    try:
        return (Path(__file__).resolve().parents[2] / "licenses" / "bb-MIT.txt").read_text(encoding="utf-8")
    except OSError:
        return "Полный текст: licenses/bb-MIT.txt в поставке приложения."


SECTIONS.append(("Заимствования и лицензии — bb",
                 "Лента ИИ адаптирована из https://github.com/get-bb/bb на PyQt.\n\n" + _bb_license()))


class HelpTab(QWidget):
    """Руководство пользователя: разделы-аккордеоны."""

    def __init__(self):
        super().__init__()
        inner = QWidget()
        layout = QVBoxLayout(inner)
        layout.setSpacing(4)
        for title, text in SECTIONS:
            btn = QToolButton()
            btn.setText(title)
            btn.setCheckable(True)
            btn.setChecked(False)
            btn.setToolButtonStyle(Qt.ToolButtonStyle.ToolButtonTextBesideIcon)
            btn.setArrowType(Qt.ArrowType.RightArrow)
            btn.setStyleSheet("QToolButton { text-align: left; padding: 6px;"
                              " font-weight: bold; border: 1px solid #888;"
                              " border-radius: 4px; }")
            body = QLabel(text)
            body.setWordWrap(True)
            body.setTextInteractionFlags(
                Qt.TextInteractionFlag.TextSelectableByMouse)
            body.setStyleSheet("padding: 4px 8px 10px 14px;")
            body.hide()
            btn.toggled.connect(
                lambda on, b=btn, w=body: (
                    b.setArrowType(Qt.ArrowType.DownArrow if on
                                   else Qt.ArrowType.RightArrow),
                    w.setVisible(on)))
            layout.addWidget(btn)
            layout.addWidget(body)
        layout.addStretch(1)

        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setWidget(inner)
        outer = QVBoxLayout(self)
        outer.setContentsMargins(0, 0, 0, 0)
        outer.addWidget(scroll)
